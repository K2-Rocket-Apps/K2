def _copy_repo(tmp_path: Path) -> Path:
    dest = tmp_path / "repo"
    shutil.copytree(
        REPO_ROOT,
        dest,
        ignore=shutil.ignore_patterns(".git", *CACHE_EXCLUDES),
    )
    # Sanity: the pristine copy passes every rule, so a later failure is the mutation's.
    for check in ALL_CHECKS:
        assert check(dest) == [], f"{check.__name__} fails on an unmodified copy"
    return dest


def _edit_json(path: Path, mutate) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    mutate(data)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


