def check_no_mcp_servers(root: Path) -> list[str]:
    """No `.mcp.json` anywhere; Codex `mcpServers == {}`; Claude has no `mcpServers`."""
    errors: list[str] = []

    for path in iter_scanned_files(root):
        if path.name == ".mcp.json":
            errors.append(f"{_rel(root, path)}: .mcp.json is not allowed anywhere in this package")

    codex, load_errors = _load_json(_codex_manifest(root))
    errors += load_errors
    if codex is not None:
        if "mcpServers" not in codex:
            errors.append(f"{_rel(root, _codex_manifest(root))}: must declare \"mcpServers\": {{}} to suppress plugin servers")
        elif codex["mcpServers"] != {}:
            errors.append(f"{_rel(root, _codex_manifest(root))}: \"mcpServers\" must be exactly {{}}")

    claude, load_errors = _load_json(_claude_manifest(root))
    errors += load_errors
    if claude is not None and "mcpServers" in claude:
        errors.append(f"{_rel(root, _claude_manifest(root))}: must not declare \"mcpServers\"")

    entries, load_errors = _marketplace_entries(root)
    errors += load_errors
    for entry in entries:
        if "mcpServers" in entry:
            errors.append(f".claude-plugin/marketplace.json: plugin {entry.get('name')!r} must not declare \"mcpServers\"")

    return errors


def check_no_hooks(root: Path) -> list[str]:
    """No hooks/ dir or hooks.json under any non-hook-permitted plugin; no `hooks` key in any plugin.json."""
    errors: list[str] = []

    for plugin_dir in _plugin_dirs(root):
        if plugin_dir.name in HOOK_PERMITTED_PLUGINS:
            continue
        for path in sorted(plugin_dir.rglob("*")):
            if path.is_dir() and path.name == "hooks":
                errors.append(f"{_rel(root, path)}/: hooks directories are not allowed in plugin {plugin_dir.name!r}")
            elif path.name == "hooks.json":
                errors.append(f"{_rel(root, path)}: hooks.json is not allowed in plugin {plugin_dir.name!r}")

    for manifest in _all_plugin_manifests(root):
        rel = manifest.relative_to(root).parts
        owner = rel[1] if len(rel) > 2 and rel[0] == "plugins" else None
        if owner in HOOK_PERMITTED_PLUGINS:
            continue
        data, load_errors = _load_json(manifest)
        errors += load_errors
        if data is not None and "hooks" in data:
            errors.append(f"{_rel(root, manifest)}: must not declare a \"hooks\" key")

    entries, load_errors = _marketplace_entries(root)
    errors += load_errors
    for entry in entries:
        if "hooks" in entry and entry.get("name") not in HOOK_PERMITTED_PLUGINS:
            errors.append(f".claude-plugin/marketplace.json: plugin {entry.get('name')!r} must not declare \"hooks\"")

    return errors


COMPONENT_KEYS = ("commands", "workflows", "agents")


def check_skills_only(root: Path) -> list[str]:
    """The primary plugin ships skills only: no commands/ or workflows/ directory, and no
    commands/workflows/agents key in either manifest or in any marketplace plugin entry."""
    errors: list[str] = []
    plugin_dir = root / "plugins" / PRIMARY_PLUGIN
    if not plugin_dir.is_dir():
        return [f"plugins/{PRIMARY_PLUGIN}/: missing"]

    for path in sorted(plugin_dir.rglob("*")):
        if path.is_dir() and path.name in {"commands", "workflows"}:
            errors.append(f"{_rel(root, path)}/: plugin {PRIMARY_PLUGIN!r} may ship skills only")

    for manifest in (_claude_manifest(root), _codex_manifest(root)):
        data, _ = _load_json(manifest)
        if data is not None:
            for key in COMPONENT_KEYS:
                if key in data:
                    errors.append(f"{_rel(root, manifest)}: must not declare {key!r}")

    # A marketplace entry (e.g. with "strict": false) can declare components inline,
    # with no directory on disk, so every entry's keys are checked too.
    entries, load_errors = _marketplace_entries(root)
    errors += load_errors
    for entry in entries:
        for key in COMPONENT_KEYS:
            if key in entry:
                errors.append(f".claude-plugin/marketplace.json: plugin {entry.get('name')!r} must not declare {key!r}")

    return errors


def check_no_symlinks(root: Path) -> list[str]:
    """No symlink anywhere in the tree (outside .git/ and local caches).

    Path.rglob does not descend into symlinked directories, so a committed link
    such as plugins/k2/skills -> ../../tests/x would hide its target from every
    content scan while an installer might still follow it. Nothing here needs a
    link, so all of them are rejected, including links under tests/.
    """
    errors: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        current = Path(dirpath)
        rel_parts = current.relative_to(root).parts
        if (rel_parts and rel_parts[0] == ".git") or any(p in CACHE_EXCLUDES for p in rel_parts):
            dirnames[:] = []
            continue
        for name in sorted(dirnames + filenames):
            path = current / name
            if not rel_parts and name == ".git":
                continue
            if path.is_symlink():
                errors.append(f"{_rel(root, path)}: symlinks are not allowed in this package")
        dirnames[:] = [d for d in dirnames if not (current / d).is_symlink()]
    return errors


def check_plugin_allowlist(root: Path) -> list[str]:
    """Marketplace plugin names equal tests/policy/allowed_plugins.txt exactly."""
    allowed = _read_list(_policy_dir(root) / "allowed_plugins.txt")
    if not allowed:
        return ["tests/policy/allowed_plugins.txt: missing or empty"]

    entries, errors = _marketplace_entries(root)
    if errors:
        return errors

    names = [e.get("name") for e in entries]
    if len(names) != len(set(names)):
        errors.append(f".claude-plugin/marketplace.json: duplicate plugin names {names}")
    if set(names) != set(allowed):
        extra = sorted(set(names) - set(allowed), key=str)
        missing = sorted(set(allowed) - set(names))
        errors.append(
            ".claude-plugin/marketplace.json: plugin names must equal tests/policy/allowed_plugins.txt "
            f"(not allow-listed: {extra}; allow-listed but absent: {missing})"
        )

    on_disk = {d.name for d in _plugin_dirs(root)}
    for name in sorted(on_disk - set(allowed)):
        errors.append(f"plugins/{name}/: plugin directory is not on tests/policy/allowed_plugins.txt")

    return errors


def check_versions(root: Path) -> list[str]:
    """Both plugin.json versions and marketplace metadata.version are identical strict semver."""
    errors: list[str] = []
    versions: dict[str, object] = {}

    market, load_errors = _load_json(_marketplace_path(root))
    errors += load_errors
    if market is not None:
        versions[".claude-plugin/marketplace.json metadata.version"] = (market.get("metadata") or {}).get("version")

    for manifest in (_claude_manifest(root), _codex_manifest(root)):
        data, load_errors = _load_json(manifest)
        errors += load_errors
        if data is not None:
            versions[f"{_rel(root, manifest)} version"] = data.get("version")

    for where, version in versions.items():
        if not (isinstance(version, str) and SEMVER_RE.match(version)):
            errors.append(f"{where}: {version!r} is not strict semver X.Y.Z")

    if len(set(map(str, versions.values()))) > 1:
        errors.append(f"versions differ: {versions}")

    return errors


def check_no_secrets(root: Path) -> list[str]:
    """No gateway token, token assignment or hook token anywhere in the scanned tree."""
    errors: list[str] = []
    for path in iter_scanned_files(root):
        text = _read_text(path)
        if text is None:
            continue
        for lineno, line in enumerate(text.splitlines(), 1):
            for pattern in SECRET_PATTERNS:
                if pattern.search(line):
                    errors.append(f"{_rel(root, path)}:{lineno}: matches secret pattern {pattern.pattern!r}")
    return errors


def _is_hygiene_file(path: Path) -> bool:
    if path.suffix.lower() in HYGIENE_SUFFIXES:
        return True
    if path.suffix == "":
        text = _read_text(path)
        if text is not None and SHELL_SHEBANG_RE.match(text.split("\n", 1)[0]):
            return True
    return False


def check_machine_hygiene(root: Path) -> list[str]:
    """No shell/PowerShell/YAML/markdown file changes machine-wide git config or schedules jobs."""
    errors: list[str] = []
    lowered = [(p, p.lower()) for p in MACHINE_HYGIENE_PATTERNS]
    for path in iter_scanned_files(root):
        if not _is_hygiene_file(path):
            continue
        text = _read_text(path)
        if text is None:
            continue
        for lineno, line in enumerate(text.splitlines(), 1):
            low = line.lower()
            for original, needle in lowered:
                if needle in low:
                    errors.append(f"{_rel(root, path)}:{lineno}: contains {original!r}")
    return errors


def _read_hashed_denylist(path: Path) -> list[tuple[str, int]]:
    """`<sha256> <length>` pairs from the hashed denylist (comments/blank lines skipped)."""
    entries = []
    for line in _read_list(path):
        digest, _, length = line.partition(" ")
        if re.fullmatch(r"[0-9a-f]{64}", digest) and length.strip().isdigit():
            entries.append((digest, int(length)))
    return entries


def _denylisted_hits(text: str, entries: list[tuple[str, int]]) -> list[str]:
    """Hash prefixes of every denylisted string found in `text` (case-insensitive)."""
    low = text.lower()
    digests_by_len: dict[int, set[str]] = {}
    for digest, length in entries:
        digests_by_len.setdefault(length, set()).add(digest)
    hits = []
    for length, digests in digests_by_len.items():
        for start in range(0, len(low) - length + 1):
            digest = hashlib.sha256(low[start:start + length].encode("utf-8")).hexdigest()
            if digest in digests:
                hits.append(digest[:12])
                digests = digests - {digest}
                if not digests:
                    break
    return hits


def check_denylist(root: Path) -> list[str]:
    """No scanned file path or line contains a denylisted string (matched by SHA-256)."""
    entries = _read_hashed_denylist(_policy_dir(root) / "denylist.sha256")
    if not entries:
        return ["tests/policy/denylist.sha256: missing or empty"]

    errors: list[str] = []
    for path in iter_scanned_files(root):
        rel = _rel(root, path)
        for hit in _denylisted_hits(rel, entries):
            errors.append(f"{rel}: path contains denylisted string (sha256 {hit}…)")
        text = _read_text(path)
        if text is None:
            continue
        for lineno, line in enumerate(text.splitlines(), 1):
            for hit in _denylisted_hits(line, entries):
                errors.append(f"{rel}:{lineno}: contains denylisted string (sha256 {hit}…)")
    return errors


ALL_CHECKS = (
    check_no_mcp_servers,
    check_no_hooks,
    check_skills_only,
    check_no_symlinks,
    check_plugin_allowlist,
    check_versions,
    check_no_secrets,
    check_machine_hygiene,
    check_denylist,
)


