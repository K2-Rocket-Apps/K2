def _with_test_marker(root: Path) -> Path:
    """Append a synthetic denylist entry so negative tests never spell a real one."""
    line = f"{hashlib.sha256(MARKER.encode()).hexdigest()} {len(MARKER)}\n"
    with (_policy_dir(root) / "denylist.sha256").open("a", encoding="utf-8") as fh:
        fh.write(line)
    return root


