@pytest.mark.parametrize("check", ALL_CHECKS, ids=lambda c: c.__name__)
def test_repo_passes(check):
    errors = check(REPO_ROOT)
    assert errors == [], "\n".join(errors)


def test_denylist_is_seeded():
    entries = _read_hashed_denylist(_policy_dir(REPO_ROOT) / "denylist.sha256")
    assert len(entries) == len(set(entries)) >= 15
    # Deliberately absent so an opt-in plugin of that name is not blocked by accident.
    assert hashlib.sha256(b"memory-hooks").hexdigest() not in {d for d, _ in entries}


def test_denylist_file_has_no_plain_text_entries():
    path = _policy_dir(REPO_ROOT) / "denylist.sha256"
    raw = [line for line in _read_list(path)]
    assert len(raw) == len(_read_hashed_denylist(path))
    assert not (_policy_dir(REPO_ROOT) / "denylist.txt").exists()


MARKER = "zz-test-banned-marker"


def _with_test_marker(root: Path) -> Path:
    """Append a synthetic denylist entry so negative tests never spell a real one."""
    line = f"{hashlib.sha256(MARKER.encode()).hexdigest()} {len(MARKER)}\n"
    with (_policy_dir(root) / "denylist.sha256").open("a", encoding="utf-8") as fh:
        fh.write(line)
    return root


