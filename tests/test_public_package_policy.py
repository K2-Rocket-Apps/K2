"""Public-package policy for this repository.

This repo is published anonymously to Claude Code and Codex users, so CI
enforces what the package must never contain: an MCP server entry, hooks,
commands, a symlink, an unlisted plugin, mismatched versions, a secret, a
command that changes machine-wide settings, or any internal string from the
denylist.

Each rule is ONE named function, `check_<rule>(root) -> list[str]`, returning
human-readable errors (an empty list means the rule passes). Later work must
relax a rule through a narrow allow-rule in its own function, never by
deleting a check. The `test_*_rejects_*` cases at the bottom copy the repo to
`tmp_path`, apply one forbidden mutation, and prove the named check catches it.

Scan scope: the whole repo tree except `.git/` and `tests/` (which includes
`tests/policy/`). The denylist is stored only as SHA-256 hashes
(`tests/policy/denylist.sha256`) so this public repo never spells out the
internal strings it guards against. `scripts/` and `.github/` ARE scanned. Local tool caches that are
never committed (`__pycache__/`, `.pytest_cache/`, `node_modules/`) are
skipped as well, since they are generated by running the checks themselves.
"""

import hashlib
import json
import os
import re
import shutil
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent

ROOT_EXCLUDES = frozenset({".git", "tests"})
CACHE_EXCLUDES = frozenset({"__pycache__", ".pytest_cache", "node_modules"})

PRIMARY_PLUGIN = "k2"

# Plugins that may ship hooks. Empty today: the hooks ban applies to every
# plugin directory. A future opt-in hooks plugin is added here by name (and
# must also be on tests/policy/allowed_plugins.txt). PRIMARY_PLUGIN may never
# be added; test_primary_plugin_is_never_hook_permitted pins that.
HOOK_PERMITTED_PLUGINS: frozenset[str] = frozenset()

SEMVER_RE = re.compile(r"^\d+\.\d+\.\d+$")

SECRET_PATTERNS = (
    re.compile(r"mgw_[A-Za-z0-9]{8,}"),
    re.compile(re.escape("MCP_GATEWAY_TOKEN=")),
    re.compile(re.escape("MEMORY_HOOK_TOKEN")),
)

MACHINE_HYGIENE_PATTERNS = (
    "git config --global",
    "safe.directory",
    "insteadOf",
    "launchctl",
    "systemctl --user",
    "schtasks",
    "Register-ScheduledTask",
    "crontab",
)
SHELL_SUFFIXES = frozenset({".sh", ".bash", ".zsh", ".ksh", ".fish"})
POWERSHELL_SUFFIXES = frozenset({".ps1", ".psm1", ".psd1"})
YAML_SUFFIXES = frozenset({".yml", ".yaml"})
MARKDOWN_SUFFIXES = frozenset({".md", ".markdown", ".mdx"})
HYGIENE_SUFFIXES = SHELL_SUFFIXES | POWERSHELL_SUFFIXES | YAML_SUFFIXES | MARKDOWN_SUFFIXES
SHELL_SHEBANG_RE = re.compile(r"^#!.*\b(sh|bash|zsh|ksh|fish|pwsh|powershell)\b")


# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------


def _policy_dir(root: Path) -> Path:
    return root / "tests" / "policy"


def _read_list(path: Path) -> list[str]:
    """Non-blank, non-comment lines of a policy list file, stripped."""
    if not path.exists():
        return []
    lines = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            lines.append(line)
    return lines


def _rel(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def iter_scanned_files(root: Path):
    """Every file the policy scans, in a stable order."""
    for path in sorted(root.rglob("*")):
        rel_parts = path.relative_to(root).parts
        if rel_parts[0] in ROOT_EXCLUDES:
            continue
        if any(part in CACHE_EXCLUDES for part in rel_parts):
            continue
        if path.is_file() or (path.is_symlink() and not path.is_dir()):
            yield path


def _read_text(path: Path) -> str | None:
    """File contents as text, or None for binary/unreadable files."""
    try:
        data = path.read_bytes()
    except OSError:
        return None
    if b"\x00" in data:
        return None
    return data.decode("utf-8", errors="replace")


def _load_json(path: Path) -> tuple[dict | None, list[str]]:
    if not path.exists():
        return None, [f"{path.name}: missing"]
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return None, [f"{path}: invalid JSON: {exc}"]
    if not isinstance(data, dict):
        return None, [f"{path}: top level must be a JSON object"]
    return data, []


def _marketplace_path(root: Path) -> Path:
    return root / ".claude-plugin" / "marketplace.json"


def _claude_manifest(root: Path) -> Path:
    return root / "plugins" / PRIMARY_PLUGIN / ".claude-plugin" / "plugin.json"


def _codex_manifest(root: Path) -> Path:
    return root / "plugins" / PRIMARY_PLUGIN / ".codex-plugin" / "plugin.json"


def _plugin_dirs(root: Path) -> list[Path]:
    plugins = root / "plugins"
    if not plugins.is_dir():
        return []
    return sorted(d for d in plugins.iterdir() if d.is_dir())


def _all_plugin_manifests(root: Path) -> list[Path]:
    return sorted(
        p for p in root.rglob("plugin.json")
        if p.relative_to(root).parts[0] not in ROOT_EXCLUDES
        and p.parent.name in {".claude-plugin", ".codex-plugin"}
    )


def _marketplace_entries(root: Path) -> tuple[list[dict], list[str]]:
    data, errors = _load_json(_marketplace_path(root))
    if data is None:
        return [], errors
    plugins = data.get("plugins")
    if not isinstance(plugins, list):
        return [], [".claude-plugin/marketplace.json: 'plugins' must be a list"]
    return [p for p in plugins if isinstance(p, dict)], []


